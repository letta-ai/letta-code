import { describe, expect, test } from "bun:test";
import {
  applyCommitTrailer,
  COMMIT_TRAILER_PLACEHOLDER,
  DEFAULT_COMMIT_TRAILER,
  resolveCommitTrailer,
} from "@/tools/commit-trailer";
import BashDescription from "@/tools/descriptions/Bash.md";
import ExecCommandDescription from "@/tools/descriptions/ExecCommand.md";
import { buildBashDescriptionForPlatform } from "@/tools/tool-definitions";

// The exact text the descriptions contained before the trailer became
// configurable. The default must keep producing it byte-for-byte.
const ORIGINAL_INSTRUCTION_BLOCK = [
  "   - Create the commit with a message ending with:",
  "   👾 Generated with [Letta Code](https://letta.com)",
  "",
  "   Co-Authored-By: Letta Code <noreply@letta.com>",
  "   - Run git status after the commit completes to verify success.",
].join("\n");

const ORIGINAL_EXAMPLE_BLOCK = [
  "git commit -m 'Commit message here.",
  "",
  "👾 Generated with [Letta Code](https://letta.com)",
  "",
  "Co-Authored-By: Letta Code <noreply@letta.com>'",
  "</example>",
].join("\n");

const CUSTOM_TRAILER =
  "Generated by Example Bot\n\nCo-Authored-By: Example Bot <bot@example.com>";

describe("resolveCommitTrailer", () => {
  test("uses the default block when BASH_COMMIT_TRAILER is unset", () => {
    expect(resolveCommitTrailer({})).toBe(DEFAULT_COMMIT_TRAILER);
    expect(DEFAULT_COMMIT_TRAILER).toBe(
      "👾 Generated with [Letta Code](https://letta.com)\n\nCo-Authored-By: Letta Code <noreply@letta.com>",
    );
  });

  test("accepts a multi-line value with real newlines", () => {
    expect(
      resolveCommitTrailer({ BASH_COMMIT_TRAILER: `  ${CUSTOM_TRAILER}\n` }),
    ).toBe(CUSTOM_TRAILER);
  });

  test("expands literal \\n escapes and normalizes CRLF", () => {
    expect(
      resolveCommitTrailer({
        BASH_COMMIT_TRAILER:
          "Generated by Example Bot\\n\\nCo-Authored-By: Example Bot <bot@example.com>",
      }),
    ).toBe(CUSTOM_TRAILER);
    expect(
      resolveCommitTrailer({
        BASH_COMMIT_TRAILER:
          "Generated by Example Bot\r\n\r\nCo-Authored-By: Example Bot <bot@example.com>",
      }),
    ).toBe(CUSTOM_TRAILER);
  });

  test("falls back to the default for empty or whitespace-only values", () => {
    for (const value of ["", "   ", "\n\t ", "\\n\\n", "  \\n  "]) {
      expect(resolveCommitTrailer({ BASH_COMMIT_TRAILER: value })).toBe(
        DEFAULT_COMMIT_TRAILER,
      );
    }
  });
});

describe("tool descriptions", () => {
  test("Bash and ExecCommand descriptions carry the trailer placeholder", () => {
    for (const description of [BashDescription, ExecCommandDescription]) {
      expect(description.split(COMMIT_TRAILER_PLACEHOLDER).length - 1).toBe(2);
      expect(description).not.toContain("Co-Authored-By:");
    }
  });

  test("the default reproduces the original text exactly", () => {
    for (const description of [BashDescription, ExecCommandDescription]) {
      const rendered = applyCommitTrailer(description, DEFAULT_COMMIT_TRAILER);
      expect(rendered).not.toContain(COMMIT_TRAILER_PLACEHOLDER);
      expect(rendered).toContain(ORIGINAL_INSTRUCTION_BLOCK);
      expect(rendered).toContain(ORIGINAL_EXAMPLE_BLOCK);
    }
  });

  test("a multi-line trailer replaces the whole block", () => {
    for (const description of [BashDescription, ExecCommandDescription]) {
      const rendered = applyCommitTrailer(description, CUSTOM_TRAILER);
      expect(rendered).not.toContain(COMMIT_TRAILER_PLACEHOLDER);
      expect(rendered).not.toContain("Co-Authored-By: Letta Code");
      expect(rendered).toContain(
        [
          "   - Create the commit with a message ending with:",
          "   Generated by Example Bot",
          "",
          "   Co-Authored-By: Example Bot <bot@example.com>",
          "   - Run git status",
        ].join("\n"),
      );
      expect(rendered).toContain(
        [
          "git commit -m 'Commit message here.",
          "",
          "Generated by Example Bot",
          "",
          "Co-Authored-By: Example Bot <bot@example.com>'",
        ].join("\n"),
      );
    }
  });

  test("the built Bash description has no leftover placeholder", () => {
    expect(buildBashDescriptionForPlatform("linux")).not.toContain(
      COMMIT_TRAILER_PLACEHOLDER,
    );
  });
});
